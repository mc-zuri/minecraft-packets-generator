'use strict'

const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('fs')
const os = require('os')
const path = require('path')
const bump = require('./newVersion')

test('new versions retain shared recipes and exclude generated files', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'packetgen-bump-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  fs.mkdirSync(path.join(root, 'mc/26.3/src'), { recursive: true })
  fs.mkdirSync(path.join(root, 'mc/26.3/run'), { recursive: true })
  fs.mkdirSync(path.join(root, 'shared/packetshapes'), { recursive: true })
  fs.writeFileSync(path.join(root, 'versions.json'), '["26.3"]')
  fs.writeFileSync(path.join(root, 'mc/26.3/build.gradle'), 'version "26.3"\n')
  fs.writeFileSync(path.join(root, 'mc/26.3/src/Example.java'), 'source')
  fs.writeFileSync(path.join(root, 'mc/26.3/run/world.dat'), 'generated')
  fs.writeFileSync(path.join(root, 'shared/packetshapes/26.3.sources'), '1.20.5/Example.java\n')
  bump('26.4', root)
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(root, 'versions.json'))), ['26.3', '26.4'])
  assert.equal(fs.readFileSync(path.join(root, 'mc/26.4/build.gradle'), 'utf8'), 'version "26.4"\n')
  assert.equal(fs.readFileSync(path.join(root, 'mc/26.4/src/Example.java'), 'utf8'), 'source')
  assert.equal(fs.readFileSync(path.join(root, 'shared/packetshapes/26.4.sources'), 'utf8'), '1.20.5/Example.java\n')
  assert.equal(fs.existsSync(path.join(root, 'mc/26.4/run')), false)
  assert.throws(() => bump('26.4', root), /already exists/)
  assert.throws(() => bump('../outside', root), /module name/)
})
